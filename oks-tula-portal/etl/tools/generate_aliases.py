def build(entries, cleaner):
    table = {}
    for canonical, variants, note in entries:
        keys = {alias_key(cleaner(canonical))}
        for v in variants:
            keys.add(alias_key(cleaner(v)))
        for k in keys:
            if not k:
                continue
            if k in table and table[k]['canonical'] != canonical:
                raise SystemExit(f'Конфликт ключа {k}: {table[k]["canonical"]} vs {canonical}')
            table[k] = {'canonical': canonical, 'note': note}
    return table

def emit_ts(table: dict) -> str:
    lines = []
    for k in sorted(table):
        v = table[k]
        note = f", note: {v['note']!r}".replace("'", '"') if v.get('note') else ''
        canonical = v['canonical'].replace("'", "\\'")
        lines.append(f"  {k}: {{ canonical: '{canonical}'{note} }},")
    return '\n'.join(lines)

