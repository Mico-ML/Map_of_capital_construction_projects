import re

def clean_org(raw: str) -> str:
    """Зеркалит normalizeOrgName (etl/src/normalize.ts) до стадии ключа."""
    s = raw.replace('\u00a0', ' ').replace('\u2009', ' ')
    s = re.sub(r'\s+', ' ', s).strip()
    # кавычки -> «ёлочки» (переключателем)
    out, open_q = [], True
    for ch in s:
        if ch == '"':
            out.append('«' if open_q else '»')
            open_q = not open_q
        else:
            out.append(ch)
    s = ''.join(out)
    # пробел после оргформы
    s = re.sub(r'\b(ООО|ОАО|ЗАО|АО|МУП|ГУП|ППК|ФКУ|МАУ|ГПОУ|ГУК|ГУЗ|ГУ|МУ)(?=[«А-ЯЁ])', r'\1 ', s)
    # ролевой суффикс
    s = re.sub(r'\s*\((?:ПИР|СМР)\)\s*$', '', s)
    # хвостовые контрактные реквизиты
    m = re.search(r'\s*[,;]?\s*№+\s*([0-9A-Za-zА-Яа-я.\-\/]+)(?:\s+от\s+(\d{2}\.\d{2}\.\d{4}))?\s*$', s)
    if m:
        s = s[:m.start()]
    # ведущие контрактные реквизиты
    m = re.match(r'^\s*№+\s*([0-9A-Za-zА-Яа-я.\-\/]+)\s+от\s+(\d{2}\.\d{2}\.\d{4})\s+', s)
    if m:
        s = s[m.end():]
    # составной заказчик «ГУКС "ТулоблУКС", АМО г. Донской» — первая часть
    s = re.split(r',\s*(?=АМО\b)', s)[0]
    return s.strip(' ,;')

def clean_program(raw: str) -> str:
    """Зеркалит normalizeProgramName (etl/src/normalize.ts)."""
    s = raw.replace('\u00a0', ' ').replace('\u2009', ' ')
    s = re.sub(r'\s+', ' ', s).strip()
    s = re.sub(r'\s*РП\s*:?\s*.*$', '', s)  # подпрограмма — в raw
    for pat in (r'^ГП\s*:\s*', r'^ГП\s+ТО\s+', r'^ГП\s+РФ\s+', r'^ГП\s+', r'^НП\s+', r'^ФП\s+',
                r'^[Гг]осударственная программа (?:Российской Федерации|Тульской области)\s*'):
        s = re.sub(pat, '', s)
    out, open_q = [], True
    for ch in s:
        if ch == '"':
            out.append('«' if open_q else '»')
            open_q = not open_q
        else:
            out.append(ch)
    s = ''.join(out)
    s = re.sub(r'»[а-яё]{1,2}$', '»', s)  # опечатка «...области»и»
    return s.strip(' ,;«»"')

def alias_key(s: str) -> str:
    return re.sub(r'[^0-9A-ZА-Я]', '', s.upper().replace('Ё', 'Е'))

