/** Нормализация ключа алиаса: только буквы/цифры, верхний регистр, ё→е. */
export function orgAliasKey(normalizedName: string): string {
  return normalizedName
    .toUpperCase()
    .replace(/Ё/g, 'Е')
    .replace(/[^0-9A-ZА-Я]/g, '');
}

